def match_known_title(filename: str) -> KnownTitle | None:
    stem = filename.rsplit(".", 1)[0] if "." in filename else filename
    hay = f"{stem} {filename}".replace("-", " ").replace("_", " ").casefold()
    hits = [item for item in KNOWN_TITLES if any(needle in hay for needle in item.filename_needles)]
    if len(hits) == 1:
        return hits[0]
    if len(hits) > 1:
        # Prefer the longest needle match so "the challenger sale" beats "sale".
        return max(
            hits,
            key=lambda item: max(len(n) for n in item.filename_needles if n in hay),
        )
    return None
