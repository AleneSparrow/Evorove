"""Filename → known sales title. Used only after the owner deposits a copy.

The tuple is append-only, not a freeze. A new purchased file can land in
incoming/ anytime; add needles here when the filename should be recognized.
Only CORE_CATALOG_IDS unlock SFT rows. Other mapped titles are archive.
"""

