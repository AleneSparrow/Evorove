def _observed_stage(rule: dict[str, Any]) -> str:
    if rule.get("requires_human"):
        return "HUMAN_REVIEW"
    objections = rule.get("objections") or []
    unresolved = [row for row in objections if row.get("status") not in {"RESOLVED", "DEFERRED"}]
    if unresolved:
        return "OBJECTION_HANDLING"
    return rule["stage"]


def _analyzer_row(rule: dict[str, Any]) -> dict[str, Any]:
    observed = _observed_stage(rule)
    commitment = rule.get("commitment") or "CONSIDERING"
    if "commitment" not in rule:
        if observed in {"DISCOVERY", "GREETING"}:
            commitment = "CURIOUS"
        if observed in {"NEEDS_CONFIRMED", "PRESENTATION"} and not rule.get("objections"):
            commitment = "INTERESTED"
        if rule["move"] in {"OFFER_BOOKING_SLOTS"}:
            commitment = "READY_FOR_NEXT_STEP"
        if rule["slug"] in {"rejection-not-pressure", "stop-ends-cadence"}:
            commitment = "DECLINED"
    rec = rule.get("rec") or rule["move"]
    requires_human = bool(rule.get("requires_human"))
    if requires_human:
        rec = "HANDOFF_TO_HUMAN"
    profile = {
        "stage": rule["stage"],
        "current_problem": "missed leads",
        "desired_outcome": "faster follow-up",
    }
    if rule.get("outbound"):
        profile["outbound"] = True
    return {
        "id": f"an-rule-{rule['catalog']}-{rule['slug']}",
        "task": "analyzer",
        "polarity": rule["polarity"],
        "catalog_id": rule["catalog"],
        "source_chunk": rule["chunk"],
        "customer_message": rule["customer"],
        "profile_context": profile,
        "target": {
            "observed_stage": observed,
            "confidence": 0.8,
            "customer_intent": rule["intent"],
            "signals": rule.get("signals")
            or (
                []
                if rule.get("objections")
                else [
                    {
                        "kind": "customer_goal",
                        "value": rule["intent"],
                        "evidence": rule["evidence"],
                    }
                ]
            ),
            "objections": rule.get("objections") or [],
            "commitment_level": commitment,
            "recommended_moves": [rec] if isinstance(rec, str) else list(rec),
            "requested_callback_at": None,
            "requires_human": requires_human,
        },
    }


def _generator_row(rule: dict[str, Any]) -> dict[str, Any]:
    facts = list(rule.get("facts") or [])
    knowledge = list(rule.get("knowledge") or [])
    row: dict[str, Any] = {
        "id": f"gen-rule-{rule['catalog']}-{rule['slug']}",
        "task": "generator",
        "polarity": rule["polarity"],
        "catalog_id": rule["catalog"],
        "source_chunk": rule["chunk"],
        "approved_move": rule["move"],
        "sales_stage": rule["stage"],
        "channel": rule.get("channel") or "chat",
        "customer_message": rule["customer"],
        "target": {
            "move": rule["move"],
            "message_text": rule["message"],
            "knowledge_ids": knowledge,
            "business_fact_ids": facts,
            "customer_evidence_ids": ["ev-1"] if rule["evidence"] else [],
            "used_safe_fallback": bool(rule.get("used_safe_fallback")),
        },
        "forbidden_patterns": list(rule.get("forbidden") or ()),
    }
    if facts:
        row["allowed_business_fact_ids"] = facts
    if knowledge:
        row["allowed_knowledge_ids"] = knowledge
    if rule.get("bad"):
        row["bad_message_text"] = rule["bad"]
    return row


def rows_from_rulebook(catalog_id: str) -> tuple[list[dict], list[dict]]:
    analyzer: list[dict] = []
    generator: list[dict] = []
    if catalog_id not in CORE_CATALOG_IDS:
        return analyzer, generator
    for rule in RULES:
        if rule["catalog"] != catalog_id:
            continue
        analyzer.append(deepcopy(_analyzer_row(rule)))
        generator.append(deepcopy(_generator_row(rule)))
    return analyzer, generator


def candidate_cards() -> list[dict[str, Any]]:
    cards = []
    for rule in RULES:
        if rule["catalog"] not in CORE_CATALOG_IDS:
            continue
        cards.append(
            {
                "knowledge_id": f"candidate-rule-{rule['catalog']}-{rule['slug']}",
                "status": "candidate",
                "version": 0,
                "catalog_id": rule["catalog"],
                "source": {
                    "chunk": rule["chunk"],
                    "provenance_confidence": "page-located",
                },
                "principle": rule["intent"],
                "maps_to_move": rule["move"],
                "polarity": rule["polarity"],
                "note": "Paraphrase only. Do not import or approve. Spec 0.4 binds.",
            }
        )
    return cards
